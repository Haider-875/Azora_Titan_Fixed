-- AZORA LEAD / EVENT STORAGE
-- Run this whole file in Supabase SQL Editor.
-- Before running, replace YOUR_ADMIN_EMAIL with the email you will use for dashboard login.

create table if not exists public.azora_leads (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event_type text not null default 'quote_submitted',
  ref text,
  business text,
  contact text,
  email text,
  phone text,
  locations text,
  message text,
  items jsonb not null default '[]'::jsonb,
  page_url text,
  user_agent text
);

alter table public.azora_leads enable row level security;

-- Public visitors may submit a lead, but cannot read/update/delete any lead.
drop policy if exists "public_can_insert_leads" on public.azora_leads;
create policy "public_can_insert_leads"
on public.azora_leads
for insert
to anon, authenticated
with check (true);

-- Only the single configured dashboard email can read leads.
drop policy if exists "admin_can_read_leads" on public.azora_leads;
create policy "admin_can_read_leads"
on public.azora_leads
for select
to authenticated
using ((select auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL');

-- No browser user can modify/delete stored leads.
revoke update, delete on public.azora_leads from anon, authenticated;
grant insert on public.azora_leads to anon, authenticated;
grant select on public.azora_leads to authenticated;

-- Optional: prevent anonymous users from querying this table through the Data API.
-- RLS already blocks SELECT for anon because no anon SELECT policy exists.

create index if not exists azora_leads_created_at_idx
on public.azora_leads (created_at desc);

create index if not exists azora_leads_event_type_idx
on public.azora_leads (event_type);
